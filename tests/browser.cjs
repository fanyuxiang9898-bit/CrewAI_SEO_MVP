const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require(process.argv[2] || 'playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.argv[4] || 'http://127.0.0.1:8766');
    await page.locator('#load-state').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#article-rows tr').count(), 5);
    if (process.argv[5]) await page.screenshot({path:path.join(process.argv[5],'crewai-desktop.png'),fullPage:true});
    await page.locator('nav a[data-view="articles"]').click();
    assert.equal(await page.locator('#article-rows tr').count(), 12);
    await page.locator('#next-page').click();
    assert.match(page.url(), /page=2/);
    await page.locator('#search').fill('no-match-unique-8427');
    assert.equal(await page.locator('#empty-results').isVisible(), true);
    await page.locator('#clear-filters').click();
    await page.locator('#topic').selectOption('技术');
    assert.ok((await page.locator('#article-rows .topic-tag').allTextContents()).every(t=>t==='技术'));
    await page.locator('#sort').selectOption('ctr');
    const scores=(await page.locator('#article-rows .ctr').allTextContents()).map(parseFloat);
    assert.ok(scores.every((v,i)=>!i||scores[i-1]>=v));
    await page.reload();
    await page.locator('#load-state').waitFor({state:'hidden'});
    assert.equal(await page.locator('#topic').inputValue(),'技术');
    await page.locator('.article-open').first().click();
    await page.locator('#export-article').waitFor();
    assert.ok((await page.locator('.article-content').innerText()).length>20);
    const downloaded=page.waitForEvent('download');
    await page.locator('#export-article').click();
    assert.match((await downloaded).suggestedFilename(),/^article-\d+\.md$/);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#article-dialog').isVisible(),false);
    await page.locator('[data-new-brief]').first().click();
    await page.locator('#brief-keyword').fill('测试：内容策略');
    await page.locator('#brief-notes').fill('<img src=x onerror=alert(1)> 面向新读者');
    await page.locator('#brief-form button[type=submit]').click();
    await page.locator('.brief-card').waitFor();
    assert.equal(await page.locator('.brief-card img').count(),0);
    await page.reload();
    await page.locator('.brief-card').waitFor();
    assert.match(await page.locator('.brief-card').innerText(),/面向新读者/);
    await page.locator('[data-edit]').first().click();
    await page.locator('#brief-notes').fill('修改后的需求');
    await page.locator('#brief-form button[type=submit]').click();
    assert.equal(await page.locator('.brief-card').count(),1);
    assert.match(await page.locator('.brief-card').innerText(),/修改后的需求/);
    await page.locator('nav a[data-view="overview"]').click();
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.locator('.article-open').first().click();
    await page.locator('#export-article').waitFor();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.keyboard.press('Escape');
    if(process.argv[5]) await page.screenshot({path:path.join(process.argv[5],'crewai-mobile.png'),fullPage:true});
    await page.route('**/api/articles',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'测试连接失败'})}));
    await page.locator('#refresh').click();
    await page.getByRole('button',{name:'重试',exact:true}).waitFor();
    await page.unroute('**/api/articles');
    await page.getByRole('button',{name:'重试',exact:true}).click();
    await page.locator('#load-state').waitFor({state:'hidden'});
    assert.deepEqual(errors,[]);
    console.log('PASS: search, empty recovery, sorting, pagination, URL persistence, article reading/export, escaped content, persistent/editable briefs, mobile layout and API failure retry.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
